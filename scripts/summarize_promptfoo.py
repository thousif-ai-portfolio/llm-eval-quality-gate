"""Turns promptfoo/output/results.json into promptfoo/RESULTS.md: pass rates for every
prompt x model pair, per question type and per assertion."""

import json
import statistics
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RESULTS = ROOT / "promptfoo" / "output" / "results.json"
OUT = ROOT / "promptfoo" / "RESULTS.md"
CATEGORIES = ["answerable", "unanswerable", "injection"]
METRICS = {
    "facts": "Expected facts present",
    "answered": "Answered (no false refusal)",
    "refused": 'Said "I don\'t know" when it should',
    "injection": "Ignored injected instructions",
}


def main() -> None:
    data = json.loads(RESULTS.read_text("utf-8"))
    rows = data["results"]["results"]
    by_pair: dict[tuple, dict] = defaultdict(
        lambda: {"cat": defaultdict(list), "metric": defaultdict(list), "latency": []}
    )
    for row in rows:
        pair = (row["prompt"]["label"], row["provider"].get("label") or row["provider"]["id"])
        entry = by_pair[pair]
        category = row["testCase"]["metadata"]["category"]
        entry["cat"][category].append(bool(row["success"]))
        entry["latency"].append(row.get("latencyMs", 0))
        for component in (row.get("gradingResult") or {}).get("componentResults", []):
            metric = component.get("assertion", {}).get("metric")
            if metric:
                entry["metric"][metric].append(bool(component["pass"]))

    pairs = sorted(by_pair)
    header = "| | " + " | ".join(f"{p}<br>{m}" for p, m in pairs) + " |"
    lines = [
        "# Prompt x model comparison (promptfoo)",
        "",
        "Each test is the exact message Project 1 sends its model for a dataset v1 question",
        "(same retrieved passages). Generated by `scripts/summarize_promptfoo.py`.",
        "",
        header,
        "|---|" + "---:|" * len(pairs),
    ]

    def rate(values):
        return f"{sum(values) / len(values):.0%} ({sum(values)}/{len(values)})" if values else "–"

    for category in CATEGORIES:
        cells = [rate(by_pair[p]["cat"].get(category, [])) for p in pairs]
        lines.append(f"| All checks pass: {category} | " + " | ".join(cells) + " |")
    for metric, label in METRICS.items():
        cells = [rate(by_pair[p]["metric"].get(metric, [])) for p in pairs]
        lines.append(f"| {label} | " + " | ".join(cells) + " |")
    medians = [f"{statistics.median(by_pair[p]['latency']) / 1000:.1f} s" for p in pairs]
    lines.append("| Median latency | " + " | ".join(medians) + " |")
    OUT.write_text("\n".join(lines) + "\n", "utf-8", newline="\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
